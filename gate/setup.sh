#!/usr/bin/env bash
# Run once on your Mac:  bash gate/setup.sh
# Makes gate/config.php and .htaccess from your password. Upload both to Hostinger (public_html).
# To open the site up again later, delete .htaccess on the server.
set -euo pipefail
cd "$(dirname "$0")"
read -r -s -p "Choose a site password: " pw; echo
read -r -s -p "Again: " pw2; echo
[ "$pw" = "$pw2" ] || { echo "Passwords don't match."; exit 1; }
[ ${#pw} -ge 8 ] || { echo "Use at least 8 characters."; exit 1; }
salt=$(openssl rand -hex 16)
token=$(openssl rand -hex 32)
hash=$(printf '%s' "${salt}${pw}" | shasum -a 256 | cut -d' ' -f1)
cat > config.php <<PHP
<?php
// Generated by setup.sh. Never commit this file.
return ['salt' => '$salt', 'hash' => '$hash', 'token' => '$token'];
PHP
sed "s/__GATE_TOKEN__/$token/" htaccess.template > ../.htaccess
echo "Done. Upload .htaccess (site root) and gate/config.php to Hostinger. Passing a new password later: run this again and re-upload both."
